CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100)  NOT NULL UNIQUE,
    email         VARCHAR(255)  NOT NULL UNIQUE,
    password_hash VARCHAR(255)  NOT NULL,
    role          VARCHAR(20)   NOT NULL,
    enabled       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE code_repositories (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner          VARCHAR(200)  NOT NULL,
    name           VARCHAR(200)  NOT NULL,
    url            VARCHAR(500)  NOT NULL,
    default_branch VARCHAR(100)  NOT NULL DEFAULT 'main',
    description    VARCHAR(1000),
    active         BOOLEAN       NOT NULL DEFAULT TRUE,
    registered_by  BIGINT        NOT NULL REFERENCES users (id),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_repo_owner_name UNIQUE (owner, name)
);

CREATE TABLE scans (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT      NOT NULL REFERENCES code_repositories (id),
    triggered_by  BIGINT      NOT NULL REFERENCES users (id),
    status        VARCHAR(20) NOT NULL,
    branch        VARCHAR(100),
    commit_sha    VARCHAR(100),
    files_scanned INTEGER     NOT NULL DEFAULT 0,
    error_message VARCHAR(2000),
    started_at    TIMESTAMPTZ,
    completed_at  TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_scans_repository ON scans (repository_id);
CREATE INDEX idx_scans_status ON scans (status);

CREATE TABLE quality_scores (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id           BIGINT           NOT NULL UNIQUE REFERENCES scans (id) ON DELETE CASCADE,
    overall_score     DOUBLE PRECISION NOT NULL,
    maintainability   DOUBLE PRECISION NOT NULL,
    reliability       DOUBLE PRECISION NOT NULL,
    security          DOUBLE PRECISION NOT NULL,
    coverage_estimate DOUBLE PRECISION NOT NULL,
    grade             VARCHAR(2)       NOT NULL
);

CREATE TABLE code_issues (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id     BIGINT       NOT NULL REFERENCES scans (id) ON DELETE CASCADE,
    file_path   VARCHAR(1000) NOT NULL,
    line_number INTEGER,
    severity    VARCHAR(20)  NOT NULL,
    category    VARCHAR(100) NOT NULL,
    title       VARCHAR(300) NOT NULL,
    description VARCHAR(2000),
    suggestion  VARCHAR(2000)
);
CREATE INDEX idx_issues_scan ON code_issues (scan_id);
CREATE INDEX idx_issues_severity ON code_issues (severity);

CREATE TABLE generated_tests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id          BIGINT        NOT NULL REFERENCES scans (id) ON DELETE CASCADE,
    source_file_path VARCHAR(1000) NOT NULL,
    test_file_path   VARCHAR(1000) NOT NULL,
    framework        VARCHAR(50)   NOT NULL,
    test_code        TEXT          NOT NULL,
    description      VARCHAR(1000)
);
CREATE INDEX idx_tests_scan ON generated_tests (scan_id);

CREATE TABLE compliance_checks (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id  BIGINT       NOT NULL REFERENCES scans (id) ON DELETE CASCADE,
    standard VARCHAR(100) NOT NULL,
    rule     VARCHAR(300) NOT NULL,
    status   VARCHAR(20)  NOT NULL,
    details  VARCHAR(2000)
);
CREATE INDEX idx_compliance_scan ON compliance_checks (scan_id);
CREATE INDEX idx_compliance_status ON compliance_checks (status);
